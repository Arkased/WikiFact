/**
 * The named HTML entities that the scan decodes: the 5 of XML (`apos` too), the ISO 8859-1 set of HTML 4 and the
 * Latin Extended-A letters. A name is case-sensitive (`Eacute` and `eacute` differ); a `Map` holds them, so a lookup cannot read an inherited key.
 */
export const HTML_ENTITIES: ReadonlyMap<string, string> = new Map<string, string>([
  ["amp", "&"],
  ["lt", "<"],
  ["gt", ">"],
  ["quot", '"'],
  ["apos", "'"],
  ...LATIN1_NAMES.map((name, i): [string, string] => [name, String.fromCodePoint(LATIN1_START + i)]),
  ...Object.entries(LATIN_EXT_A).map(([name, code]): [string, string] => [name, String.fromCodePoint(code)]),
]);
