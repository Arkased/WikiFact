// The build of `plugin/dist/` (docs/technical/publication.md#the-plugin): 1 self-contained CommonJS file per entry of
// `plugin/src/`, with zod inside, so that `node` alone runs it from the plugin folder. `import.meta.url` is replaced by
// the URL of the bundle file, so that `isMain` works in the bundle as it does in the source.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build } from "esbuild";

/** The entry files of the plugin, as the hooks and the command name them (without the extension). */
export const PLUGIN_ENTRIES = ["setup", "wiki-context", "wiki-submit"];

/** The text of `plugin/dist/package.json`: the repo root says `"type": "module"`, and Node takes the nearest file. */
const DIST_PACKAGE = '{ "type": "commonjs" }\n';

const banner = (source: string): string =>
  `// Generated by \`npm run build\` from ${source}. Do not edit; change the source and build again.\n` +
  `const __importMetaUrl = require("node:url").pathToFileURL(__filename).href;`;

/**
 * Builds the bundles of the plugin.
 *
 * @param root - the project root, which holds `plugin/src/`
 * @param outDir - the folder to build into; it is emptied first, so that a removed entry leaves no bundle behind
 * @sideEffects deletes and makes `outDir`; writes one bundle per entry and `package.json` in it
 */
export async function buildPlugin(root: string, outDir: string): Promise<void> {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "package.json"), DIST_PACKAGE);
  for (const name of PLUGIN_ENTRIES) {
    await build({
      entryPoints: [join(root, "plugin", "src", `${name}.ts`)],
      outfile: join(outDir, `${name}.js`),
      bundle: true,
      platform: "node",
      format: "cjs",
      target: "node22",
      legalComments: "none",
      define: { "import.meta.url": "__importMetaUrl" },
      banner: { js: banner(`plugin/src/${name}.ts`) },
      logLevel: "warning",
    });
  }
}
